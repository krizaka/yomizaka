import { readFileSync } from "node:fs";
import { join } from "node:path";

import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it } from "vitest";

import en from "@/messages/en.json";
import fr from "@/messages/fr.json";

import { HeroFlow } from "../components/home/HeroFlow";
import { HERO_RULE } from "./landing";
import { recordedRun } from "./recorded-runs";

const ROOT = join(__dirname, "..");
const css = readFileSync(join(ROOT, "components/home/hero-flow.css"), "utf8");

describe("the hero's continuous flow", () => {
  const run = recordedRun("tenant");
  const html = renderToStaticMarkup(createElement(HeroFlow, { locale: "fr" }));

  it("has the six steps of the journey: drop → read → rules → finding → report → share", () => {
    expect(html.match(/data-scene="\d"/g)).toHaveLength(6);
    for (const label of Object.values(fr.landing.flow.rail)) expect(html).toContain(label);
    expect(Object.keys(en.landing.flow.rail)).toEqual(["drop", "read", "rules", "finding", "report", "share"]);
  });

  it("ticks the real rules of the recorded run — every rule id, with its verdict — and lights the real finding with its article", () => {
    for (const f of run.report.findings) expect(html).toContain(f.ruleId);
    const verdicts = [...html.matchAll(/class="hf-(pass|fail|unk)">/g)].length;
    expect(verdicts).toBe(run.report.findings.length);
    const finding = run.report.findings.find((f) => f.ruleId === HERO_RULE)!;
    expect(html).toContain(finding.citation!.replace(/&/g, "&amp;"));
    expect(html).toContain("hf-lit");
    expect(html).toContain(run.runId.slice(0, 8));
  });

  it("shows the specimen honestly: an illustration, unsigned, never a file — and no key material", () => {
    expect(html).toContain(fr.landing.flow.signed);
    expect(fr.landing.flow.caption).toMatch(/spécimen/i);
    expect(en.landing.flow.caption).toMatch(/specimen/i);
    expect(html).not.toMatch(/ed25519|keyId|attestation|\.pdf|download/i);
  });

  it("is CSS only: no client component, no script, and the loop moves transforms and opacity on the compositor", () => {
    const source = readFileSync(join(ROOT, "components/home/HeroFlow.tsx"), "utf8");
    expect(source).not.toContain('"use client"');
    expect(source).not.toMatch(/useEffect|requestAnimationFrame|<canvas|setInterval/);
    const keyframes = [...css.matchAll(/@keyframes [\w-]+\{[^@]*?\}\}/g)].map((m) => m[0]).join("\n");
    expect(keyframes.length).toBeGreaterThan(500);
    // Nothing that triggers layout: no width/height/top/left/margin in a keyframe (the scan moves by translateY).
    expect(keyframes).not.toMatch(/(?<![-\w])(width|height|top|left|right|bottom|margin|padding)\s*:/);
  });

  it("does not run under prefers-reduced-motion: the final state is shown, the first two scenes hidden", () => {
    const outside = css.slice(0, css.indexOf("@media (prefers-reduced-motion:no-preference)"));
    expect(css).toContain("@media (prefers-reduced-motion:no-preference)");
    expect(outside).not.toContain("animation:");
    expect(outside).toContain(".hf-scene[data-scene='1'],.hf-scene[data-scene='2']{display:none}");
  });

  it("is one 20 s loop whose six scenes follow each other, and the stylesheet is the generator's output", () => {
    expect(css).toContain("--hf-cycle:20s");
    expect(css).toContain("GENERATED by apps/web/scripts/gen-hero-flow-css.py");
    for (let i = 1; i <= 6; i++) expect(css).toContain(`@keyframes hf-s${i}`);
    expect(readFileSync(join(ROOT, "scripts/gen-hero-flow-css.py"), "utf8")).toContain("CYCLE=20.0");
  });
});
