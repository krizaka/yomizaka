import "./hero-flow.css";

import { CheckIcon, LockIcon } from "@krizaka/icons";
import { Mascot } from "@krizaka/ui/mascots";
import { passages } from "@yomizaka/core";

import { getDictionary, type Locale } from "@/lib/i18n";
import { HERO_RULE } from "@/lib/landing";
import { recordedRun } from "@/lib/recorded-runs";

const GLYPH = { PASS: ["✓", "hf-pass"], FAIL: ["✕", "hf-fail"], INSUFFICIENT_EVIDENCE: ["?", "hf-unk"] } as const;

/**
 * The hero's proof: one continuous flow, from the file to the shared report — drop the lease → the owl reads it (a scan
 * crosses the lines) → the rules run (the checklist ticks, with the real rule ids) → the finding lit with its article → the
 * report, signed → shared with a member. Every word and rule is read from the recorded run (content/recorded-runs/tenant.json);
 * the motion is CSS only (transform and opacity, one 20 s loop, no script — hero-flow.css is generated by
 * scripts/gen-hero-flow-css.py). Under prefers-reduced-motion the loop does not run: the final state is shown. The report
 * drawn here is an illustration of a specimen — unsigned, never a file (ADR-0002).
 */
export function HeroFlow({ locale }: { locale: Locale }) {
  const d = getDictionary(locale);
  const t = d.landing.flow;
  const run = recordedRun("tenant");
  const finding = run.report.findings.find((f) => f.ruleId === HERO_RULE)!;
  const quote = finding.evidenceSpan?.quote;
  const text = run.document.text;
  const lines = text.split("\n");
  const at = quote ? lines.findIndex((l) => l.includes(quote)) : -1;
  const excerpt = at >= 0 ? lines.slice(Math.max(0, at - 2), at + 3).join("\n") : text;
  const parts = passages(excerpt, quote ? [{ id: finding.ruleId, quote }] : []);
  const fails = run.report.findings.filter((f) => f.verdict === "FAIL").length;
  const passes = run.report.findings.filter((f) => f.verdict === "PASS").length;
  const rail = [t.rail.drop, t.rail.read, t.rail.rules, t.rail.finding, t.rail.report, t.rail.share];
  return (
    <div className="hf" data-testid="hero-flow" role="group" aria-label={t.label}>
      <ol className="hf-rail" aria-hidden>
        {rail.map((label) => (
          <li key={label}>
            <i />
            {label}
          </li>
        ))}
      </ol>
      <div className="hf-stage">
        {/* 1 · the lease is dropped */}
        <div className="hf-scene" data-scene="1" aria-hidden>
          <div className="hf-dropzone">
            <span>{t.dropTitle}</span>
            <span className="hf-file hf-mono" data-drop>
              {run.document.filename}
            </span>
          </div>
        </div>
        {/* 2 · the owl reads it */}
        <div className="hf-scene" data-scene="2" aria-hidden>
          <p className="m-0 text-xs font-semibold uppercase tracking-wider text-fg-muted">{t.reading}</p>
          <pre className="hf-lease hf-mono">
            {text}
            <span className="hf-scan" />
          </pre>
          <span className="hf-owl">
            <Mascot bird="owl" mood="thinking" size={56} />
          </span>
        </div>
        {/* 3 · the rules run */}
        <div className="hf-scene" data-scene="3">
          <p className="m-0 text-xs font-semibold uppercase tracking-wider text-fg-muted">
            {t.rulesTitle} · {run.report.findings.length}
          </p>
          <ul className="hf-rules" data-testid="hero-flow-rules">
            {run.report.findings.map((f) => {
              const [glyph, tone] = GLYPH[f.verdict as keyof typeof GLYPH] ?? GLYPH.INSUFFICIENT_EVIDENCE;
              return (
                <li key={f.ruleId} className="hf-rule">
                  <span className="min-w-0 truncate">
                    <span className="hf-mono">{f.ruleId}</span> · {f.title ?? f.ruleId}
                  </span>
                  <b className={tone}>{glyph}</b>
                </li>
              );
            })}
          </ul>
        </div>
        {/* 4 · the finding, lit, with its article */}
        <div className="hf-scene" data-scene="4">
          <pre className="hf-lease hf-mono m-0">
            {parts.map((p, i) =>
              p.mark ? (
                <mark key={i} className="hf-lit">
                  {p.text}
                </mark>
              ) : (
                <span key={i}>{p.text}</span>
              ),
            )}
          </pre>
          <div className="hf-card" data-anim data-testid="hero-flow-finding">
            <span className="text-sm font-semibold leading-snug text-fg">{finding.title}</span>
            {quote ? <span className="border-l-2 border-accent pl-2 text-sm italic text-fg-secondary">« {quote} »</span> : null}
            <span className="hf-art" data-testid="hero-article">
              {finding.citation}
            </span>
          </div>
        </div>
        {/* 5 · the report, signed (an illustrated specimen) */}
        <div className="hf-scene" data-scene="5">
          <div className="hf-sheet" data-anim>
            <span className="text-sm font-semibold text-fg">{t.reportTitle}</span>
            <span>{run.document.title}</span>
            <span className="hf-mono">
              {t.runLabel} {run.runId.slice(0, 8)}
            </span>
            <span>{t.summary.replace("{fail}", String(fails)).replace("{pass}", String(passes))}</span>
            <span className="hf-stamp" data-anim>
              <LockIcon size={14} /> {t.signed}
            </span>
          </div>
        </div>
        {/* 6 · shared with a member */}
        <div className="hf-scene" data-scene="6">
          <div className="hf-share" data-anim>
            <span className="hf-avatar" aria-hidden>
              {t.memberInitial}
            </span>
            <span className="flex min-w-0 flex-1 flex-col">
              <span className="text-sm font-semibold text-fg">{t.member}</span>
              <span className="text-xs text-fg-secondary">{t.shared}</span>
            </span>
            <span aria-hidden className="text-fg-accent [&_svg]:size-5">
              <CheckIcon />
            </span>
          </div>
        </div>
      </div>
      <p className="hf-note">{t.caption.replace("{run}", run.runId.slice(0, 8))}</p>
    </div>
  );
}
